# Generate commit message function
def _generate_git_commit_message(context_input: str = "") -> str | None:
    # 1. Check status
    status = run_command(["git", "status", "--short"])
    if not status or status.startswith("Error:"):
        return None

    # 2. Stage changes
    run_command(["git", "add", "."])
    diff_staged = run_command(["git", "diff", "--staged"])

    if not diff_staged.strip():
        diff_staged = status

    truncated_diff = diff_staged[:1000]
    context = get_context(context_input, status, truncated_diff)

    # 3. Construct prompt
    prompt = f"""
    You are an expert Git assistant and senior software developer.
    Analyze the context, staged files, and git diff below to generate a high-quality commit message following the Conventional Commits format.

    FORMAT SPECIFICATION:
    <type>(<scope>): <description>

    OPTIONAL BODY FORMAT:

    <type>(<scope>): <description>

    <body>

    RULES FOR TYPE & DESCRIPTION:
    1. Valid types: feat, fix, chore, docs, style, refactor, perf, test, build, ci, revert.
    2. Description must explain WHAT changed and WHY in imperative present tense. Keep it concise (under 60 characters).
    3. Include a short body description when helpful. The body must be under 100 words.
    4. Be specific based on actual diff content.

    CONTEXT / INTENT:
    {context}

    Status:
    {status}
    STAGED FILES & DIFF:
    {truncated_diff}

    Write ONLY the final commit message string without markdown backticks or commentary.
    If you include a body, separate it from the subject with a single blank line.
    """

    COMMAND_SCHEMA = {
    "type": "object",
    "properties": {
        "commit_message" : {"type": "string"},
    },
    "required": ["commit_message"],
    "additionalProperties": False,
    }

    commit_message = call_groq_structured(system_prompt="You are an expert Git assistant and senior software developer.", user_input=prompt, schema=COMMAND_SCHEMA, smart_model=True).get("commit_message", "")

    if not commit_message:
        return None

    return commit_message

# Execute commit function
def _execute_git_commit(commit_message: str) -> str:
    subject, body = commit_message.strip(), ""

    if "\n\n" in subject:
        subject, body = subject.split("\n\n", 1)

    command = ["git", "commit", "-m", subject]
    if body.strip():
        command.extend(["-m", body.strip()])

    run_command(command)
    run_command(["git", "push"])
    return "Changes committed and pushed successfully."

# Cancel commit function
def _cancel_git_commit() -> str:
    run_command(["git", "reset"])
    return "Commit cancelled and changes unstaged."

