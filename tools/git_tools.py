# Commit function
def git_commit(context_input: str = "") -> str:
    commit_message = _generate_git_commit_message(context_input)

    if commit_message is None:
        print("No changes detected. Nothing to commit.")
        return "No changes detected. Nothing to commit."

    print(f"\nCommit message generated by Jarvis:\n--> {commit_message}")

    # Interactive CLI Mode
    allow = input("Do you want to proceed with this commit message? (y/n): ").strip().lower()
    if allow == "y":
        _execute_git_commit(commit_message)
        return f"Changes committed and pushed successfully:\n\"{commit_message}\""

    _cancel_git_commit()
    return "Commit cancelled and changes unstaged."

# Create branch function
def git_create_branch(branch_name: str):
    command: list[str] = ["git", "switch", "-c", branch_name]
    _ = run_command(command)
    print(f"Created and switched to branch: '{branch_name}'")

# Current branch function
def git_current_branch() -> str:
    command: list[str] = ["git", "branch", "--show-current"]
    result = run_command(command)
    return result.strip()

# Delete branch function
def git_delete_branch(branch_name: str):
    command: list[str] = ["git", "branch", "-D", branch_name]
    _ = run_command(command)
    print(f"Deleted branch: '{branch_name}'")

# List branches function
def git_list_branches() -> list[str]:
    command: list[str] = ["git", "branch"]
    result = run_command(command)
    branches = [line.strip().lstrip("* ").strip() for line in result.splitlines()]
    return branches

# Switch branch function
def git_switch_branch(branch_name: str):
    command: list[str] = ["git", "switch", branch_name]
    _ = run_command(command)
    print(f"Switched to branch: '{branch_name}'")

